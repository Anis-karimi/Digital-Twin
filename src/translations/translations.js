/**
 * Get translation string for a key and language
 * @param {string} lang - 'fa' | 'en' | etc.
 * @param {string} key - translation key (e.g., 'settings')
 * @param {string} [fallback] - optional fallback string
 * @returns {string}
 */
export const getTranslation = (lang, key, fallback = "") => {
  if (translations[lang] && translations[lang][key] !== undefined) {
    return translations[lang][key];
  }
  if (translations.fa && translations.fa[key] !== undefined) {
    return translations.fa[key];
  }
  return fallback || key;
};
