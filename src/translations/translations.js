/**
 * Get translation string for a key and language
 * @param {string} lang - 'fa' | 'en' | 'ar' | etc.
 * @param {string} key - translation key (e.g., 'settings')
 * @param {string} [fallback] - optional fallback string
 * @returns {string}
 */
export const getTranslation = (lang, key, fallback = "", params = null) => {
  let val = "";
  if (translations[lang] && translations[lang][key] !== undefined) {
    val = translations[lang][key];
  } else if (translations.fa && translations.fa[key] !== undefined) {
    val = translations.fa[key];
  } else {
    val = typeof fallback === "string" ? fallback || key : key;
  }

  const interpolationParams =
    typeof fallback === "object" && fallback !== null ? fallback : params;
  if (interpolationParams && typeof val === "string") {
    Object.keys(interpolationParams).forEach((k) => {
      val = val.replaceAll(`{${k}}`, interpolationParams[k]);
    });
  }
  return val;
};

// Universal global translation helper & fallback so `t(...)` is never undefined
export const t = (key, fallback = "", params = null) => {
  const lang =
    (typeof localStorage !== "undefined" && localStorage.getItem("language")) ||
    "fa";
  return getTranslation(lang, key, fallback, params);
};

if (typeof window !== "undefined") {
  window.t = t;
}

